function pd = mexec_file_locations(filetype)
%
% mexec_file_locations(filetype)
% where filetype is one of 
% 'ctd', 'fir', 'dcs', 'win', 'sadcp', 'ladcp'
%
% mexec_file_locations('sadcp',inst,cast_select)
% where inst is e.g. 'os75nb' or 'os150bb' etc.
%
% mexec_file_locations('samp',samtyp)
% where samtyp is one of oxy, sal, nut, co2, cfc, pig, iso, log

m_common

mutv = mudefine;
dirs = {
    'M_CTD' 'ctd'
    'M_CTD_CNV' fullfile('ctd','ASCII_FILES')
    'M_CTD_BOT' fullfile('ctd','ASCII_FILES')
    'M_CTD_WIN' fullfile('ctd','WINCH')
    'M_CTD_DEP' 'station_information'
    'M_BOT'     'bottle_samples'
    'M_BOT_SAL' fullfile('bottle_samples','SAL')
    'M_BOT_OXY' fullfile('bottle_samples','OXY')
    'M_BOT_NUT' fullfile('bottle_samples','NUT')
    'M_BOT_PIG' fullfile('bottle_samples','PIG')
    'M_BOT_CO2' fullfile('bottle_samples','CO2')
    'M_BOT_CFC' fullfile('bottle_samples','CFC')
    'M_BOT_CH4' fullfile('bottle_samples','CH4')
    'M_BOT_CHL' fullfile('bottle_samples','PIG')
    'M_BOT_ISO' fullfile('bottle_samples','LOGS')
    'M_SAM' 'ctd'
    'M_SBE35' fullfile('ctd','ASCII_FILES','SBE35')
    'M_SUM' 'collected_files'
    'M_VMADCP' 'vmadcp'
    'M_NAV' 'nav'
    'M_SURFMET' 'surfmet'
    'M_BATHY' 'bathy'
    'M_UWAY_RAW' fullfile(MEXEC_G.Mshipdatasystem,'raw_local')};
if strcmp(MEXEC_G.datatypes.ladcp,'ix')
    dirs = [dirs;
        {'M_LADCP' 'ladcp'
        'M_IX' fullfile('ladcp','ix')}];
end
if exist('mutv','var')
    dirs = [dirs; ...
        [cellfun(@(x) ['M_' upper(x)], mutv.mstarpre, 'UniformOutput', false), ...
        mutv.mstardir]];
    [~,ii] = unique(dirs(:,1),'stable');
    dirs = dirs(ii,:);
end
dirs(:,2) = cellfun(@(x) fullfile(fp,x),dirs(:,2),'UniformOutput',false);
mdirlist = cell2struct(dirs(:,2),dirs(:,1));

%.nc files for different processing stages
fp = MEXEC_G.mexec_data_root;

switch filetype
    case 'ctd'
        pd.ctdrawdir = fullfile(fp,'ctd','ASCII_FILES');
        pd.ctdprocdir = fullfile(fp,'ctd');
        pd.ctdname = ['ctd_' MEXEC_G.mcruise '_%s'];
        pd.ctdraw = fullfile(pd.ctdprocdir, [pd.ctdname '_cnv.nc']);
        pd.ctdclean = fullfile(pd.ctdprocdir, [pd.ctdname '_cleaned.nc']);
        pd.ctd24 = fullfile(pd.ctdprocdir, [pd.ctdname '_24hz.nc']);
        pd.ctd1 = fullfile(pd.ctdprocdir, [pd.ctdname '_1hz.nc']);
        pd.ctd10s = fullfile(pd.ctdprocdir, [pd.ctdname '_10s.nc']);
        pd.ctd2d = fullfile(pd.ctdprocdir, [pd.ctdname '_2db.nc']);
        pd.ctd2u = fullfile(pd.ctdprocdir, [pd.ctdname '_2up.nc']);
        pd.edctd24 = fullfile(pd.ctdprocdir,'editlogs','ctd_%s_editpoints');
        pd.sbe35name = ['sbe35_' MEXEC_G.mcruise '_all'];
        pd.sbe35rawdir = fullfile(fp,'ctd','ASCII_FILES','SBE35');
        pd.sbe35 = fullfile(fp,'ctd','ASCII_FILES','SBE35', [pd.sbe35name '.nc']);
        pd.svel = fullfile(fp,'bathy', 'svel_for_echosounders', [pd.ctdname '_10s_down_svel.csv']);
        %pd.asc_forladcp_1hz
    case 'fir'
        pd.firname = ['fir_' MEXEC_G.mcruise '_%s'];
        pd.firfile = fullfile(pd.ctdprocdir, [pd.firname '.nc']);
    case 'dcs'
        pd.dcsname = ['dcs_' MEXEC_G.mcruise '_%s'];
        pd.dcsfile = fullfile(pd.ctdprocdir, [pd.dcsname '.nc']);
    case 'win'
        pd.winname = ['win_' MEXEC_G.mcruise '_%s'];
        pd.winfile = fullfile(pd.ctdprocdir_WIN, [pd.winname '.nc']);
    case 'samp'
        pd.samc = fullfile(mdirlist.M_BOT,['nisksamp_' MEXEC_G.mcruise '_all.nc']);
        pd.samu = fullfile(mdirlist.M_BOT,['ucswsamp_' MEXEC_G.mcruise '_all.nc']);
        if nargin>2
            pd.([varargin{2} 'name']) = [varargin{2} '_' MEXEC_G.mcruise '_all'];
            pd.([varargin{2}]) = fullfile(mdirlist.(['M_BOT_' upper(varargin{2})]),[pd.([varargin{2} 'name']) '.nc']);
        end
    case 'sadcp'
        if nargin>2
            pd.sadcpname = [varargin{2} '_' MEXEC_G.mcruise '_' varargin{3} '_%s'];
            pd.sadcpav = fullfile(mdirlist.M_VMADCP, 'mproc', [pd.sadcpname '_ave.nc']);
        end
        pd.sadcpall = fullfile(mdirlist.VMADCP, 'postprocessing', upper(MEXEC_G.mcruise), 'proc_editing', varargin{2}, 'contour', [pd.sadcpname '.nc']);
    case 'uway'
        pd.bunav = fullfile(mdirlist.M_NAV,['bestnav_' MEXEC_G.mcruise '_all.nc']);
        pd.buocean = fullfile(mdirlist.M_SURFMET,['surface_ocean_' MEXEC_G.mcruise '_all.nc']);
        pd.bumet = fullfile(mdirlist.M_SURFMET,['atmos_truwind_' MEXEC_G.mcruise '_all.nc']);
        pd.bubathy = fullfile(mdirlist.M_BATHY,['bathy_' MEXEC_G.mcruise '_all.nc']);
    case 'sumout'
        pd.collected = fullfile(fp,'collected_files');
    case 'ladcp'
        pd.ctdnav_for_ix = fullfile(mdirlist.M_LADCP,'ctd','ctd.%s.02.asc');
        pd.ladcpraw = fullfile(mdirlist.M_LADCP,'rawdata','%s');
        pd.sadcp_for_ix = fullfile(mdirlist.M_LADCP, 'sadcp', ['%s_' MEXEC_G.mcruise '_ctd_%s_forladcp.mat']);
end

switch type
    case {'samp','ctd'}
        pd.sg = fullfile(pd.ctdprocdir,'sensor_groups.mat'); %generated by get_sensor_groups, contains groups of sensors by serial number, sg, sng
        pd.sum = fullfile(mdirlist.M_SUM,['station_summary_' MEXEC_G.mcruise '_all.nc']);

end
